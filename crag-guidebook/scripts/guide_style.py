"""
guide_style.py — the one shared home for the house-style keys and the shade rule.

Not a command-line tool. It is imported by build_guide.py (renderer), export_geo.py
(map files), parse_guide_pdf.py (mode C: reading a guide back) and verify_guide.py.

Why one module: the PDF parser recognises a route name, a grade or a star rating by
its font size, colour and x-position. If the renderer's CSS drifts and the parser's
constants do not, the round trip silently breaks. So the parser-relevant CSS is
*generated* from the constants below (key_css()) and appended after guide.css by the
builder — change a value here and both sides move together.

Shade rule (F1): daylight D = [sunrise, sunset]; sun window W = [a, b] or none.
Shade S = D minus W = [sunrise, a) and (b, sunset]. Segments shorter than
MIN_SEGMENT_MIN are dropped; the longer remaining segment leads the phrase.
"""

