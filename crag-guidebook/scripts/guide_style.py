# ------------------------------------------------------------------ data helpers

def local_src(route):
    v = route.get('local_src')
    if v is None:
        return None
    return LOCAL_SRC_ALIASES.get(str(v).lower(), str(v).lower())


def is_top_pick(route):
    return route.get('rating') in TOP_PICK_ALIASES


def month_label(meta):
    """'June' etc. From crag.month_label, else the month of conditions_date."""
    if meta.get('month_label'):
        return meta['month_label']
    d = meta.get('conditions_date') or (meta.get('conditions_meta') or {}).get('date')
    if d and re.match(r'\d{4}-\d{2}', d):
        names = ['January', 'February', 'March', 'April', 'May', 'June', 'July',
                 'August', 'September', 'October', 'November', 'December']
        return names[int(d[5:7]) - 1]
    return 'Conditions'


# ------------------------------------------------------------------ shade (F1)

MIN_SEGMENT_MIN = 15
DEFAULT_SUNRISE, DEFAULT_SUNSET = '06:00', '20:00'


def to_min(hhmm):
    h, m = hhmm.split(':')
    return int(h) * 60 + int(m)


def daylight(meta):
    cm = (meta or {}).get('conditions_meta') or {}
    return (cm.get('sunrise') or DEFAULT_SUNRISE, cm.get('sunset') or DEFAULT_SUNSET)


def shade_segments(sun, sunrise, sunset):
    """
    Return a list of (kind, start, end, minutes) shade segments inside daylight,
    kind in {'before', 'after', 'all'}; sorted longest first; short ones dropped.
    """
    if not sun:
        return [('all', sunrise, sunset, to_min(sunset) - to_min(sunrise))]
    a, b = sun
    segs = []
    before = to_min(a) - to_min(sunrise)
    after = to_min(sunset) - to_min(b)
    if before >= MIN_SEGMENT_MIN:
        segs.append(('before', sunrise, a, before))
    if after >= MIN_SEGMENT_MIN:
        segs.append(('after', b, sunset, after))
    segs.sort(key=lambda s: -s[3])
    return segs


def shade_parts(sun, sunrise, sunset):
    """
    (main, other) phrases. Main: 'until 09:00' / 'after 13:00' / 'all day'.
    Other (the shorter segment): 'before 09:00' / 'after 18:00' / None.
    (None, None) when neither segment reaches MIN_SEGMENT_MIN.
    """
    segs = shade_segments(sun, sunrise, sunset)
    if not segs:
        return None, None
    words = []
    for i, (kind, start, end, _) in enumerate(segs):
        if kind == 'all':
            words.append('all day')
        elif kind == 'before':
            words.append(('until %s' if i == 0 else 'before %s') % end)
        else:
            words.append('after %s' % start)
    return words[0], (words[1] if len(words) > 1 else None)


def shade_headline(sector, meta):
    """The sector header phrase. Always contains the word 'Shade'."""
    if sector.get('shade_override'):
        return sector['shade_override']['headline']
    main, other = shade_parts(sector.get('sun'), *daylight(meta))
    if main is None:
        return 'Shade: hardly any (sunlit about %s–%s)' % tuple(sector['sun'])
    if main == 'all day':
        return 'Shade all day'
    return 'Shade (climbable) %s%s' % (main, (' · also %s' % other) if other else '')


def shade_table(sector, meta):
    """Contents-table cell (HTML)."""
    if sector.get('shade_override'):
        return sector['shade_override']['table']
    main, other = shade_parts(sector.get('sun'), *daylight(meta))
    if main is None:
        return 'hardly any'
    if main == 'all day':
        return 'all day'
    return '<b>%s</b>%s' % (main, ('<div class="tgr">also %s</div>' % other) if other else '')


def shade_short(sector, meta):
    """Coordinate-table cell (HTML)."""
    if sector.get('shade_override'):
        return sector['shade_override']['short']
    main, other = shade_parts(sector.get('sun'), *daylight(meta))
    if main is None:
        return 'hardly any'
    if main == 'all day':
        return 'all day'
    return main + (("<br><span class='small'>also %s</span>" % other) if other else '')


def shade_text(sector, meta):
    """Plain text for KML/GPX/CSV."""
    if sector.get('shade_override'):
        return strip_tags(sector['shade_override'].get('short', sector['shade_override']['headline']))
    main, other = shade_parts(sector.get('sun'), *daylight(meta))
    if main is None:
        return 'shade: hardly any'
    if main == 'all day':
        return 'shade all day'
    return 'shade %s%s' % (main, (', and %s' % other) if other else '')


def strip_tags(s):
    s = re.sub(r'<br\s*/?>', ' ', s or '')
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', s)).strip()
